import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { plantumlSequenceBindings } from '@dev-centr/plantuml-svg-css-vars'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const name = 'lightbox-compose'
const sourcePath = join(root, 'demo/docs/modules/ROOT/diagrams', `${name}.puml`)
const imageDir = join(root, 'demo/docs/modules/ROOT/images/diagrams')
const manifestPath = join(imageDir, `${name}.theme.json`)
const hostCssPath = join(root, 'demo/supplemental-ui/css/site-themed-svg.css')
const adapter = join(root, 'node_modules/@dev-centr/plantuml-svg-css-vars/bin/plantuml-svg-css-vars.js')
const check = process.argv.includes('--check')

const palettes = {
  light: {
    'color.canvas': '#ffffff',
    'color.surface.primary': '#eef2ff',
    'color.surface.secondary': '#f8fafc',
    'color.text.primary': '#172033',
    'color.border.primary': '#5b6475',
    'color.edge': '#475569',
    'color.status.warning': '#fef9c3',
    'color.status.warning-border': '#854d0e',
  },
  dark: {
    'color.canvas': '#111827',
    'color.surface.primary': '#273449',
    'color.surface.secondary': '#1f2937',
    'color.text.primary': '#f8fafc',
    'color.border.primary': '#a5b4c7',
    'color.edge': '#cbd5e1',
    'color.status.warning': '#422006',
    'color.status.warning-border': '#facc15',
  },
}

const namespace = `facto-stack-demo-${name}`

function manifestJson () {
  return `${JSON.stringify({
    $schema: 'https://docs.devcentr.org/themed-svg/schemas/themed-svg-manifest-v1.schema.json',
    schemaVersion: 1,
    namespace,
    source: { kind: 'plantuml', generator: 'kroki-plantuml', uri: `${name}.puml` },
    tokens: Object.keys(palettes.light).map((id) => ({ id })),
    defaultPreset: 'light',
    presets: palettes,
    bindings: plantumlSequenceBindings(),
    fallback: { unresolvedToken: 'error', missingTarget: 'warn' },
  }, null, 2)}\n`
}

function cssVar (tokenId) {
  return `--themed-svg-${namespace}-${tokenId.replaceAll('.', '-')}`
}

function hostCssBlock () {
  const lines = [
    '/* Demo PlantUML Themed SVG host vars (lightbox-compose). Generated by scripts/build-demo-plantuml.mjs */',
    ':root {',
  ]
  for (const [id, value] of Object.entries(palettes.light)) lines.push(`  ${cssVar(id)}: ${value};`)
  lines.push('}', '', 'html.dark-theme {')
  for (const [id, value] of Object.entries(palettes.dark)) lines.push(`  ${cssVar(id)}: ${value};`)
  lines.push('}', '')
  return lines.join('\n')
}

async function fetchKrokiSvg (source) {
  const res = await fetch('https://kroki.io/plantuml/svg', {
    method: 'POST',
    headers: { 'Content-Type': 'text/plain;charset=UTF-8' },
    body: source,
  })
  if (!res.ok) throw new Error(`Kroki plantuml/svg ${res.status}: ${await res.text()}`)
  return res.text()
}

const manifest = manifestJson()
if (check) {
  if (!existsSync(manifestPath) || readFileSync(manifestPath, 'utf8') !== manifest) {
    throw new Error(`${basename(manifestPath)} is stale — run pnpm diagrams:demo-plantuml`)
  }
} else {
  writeFileSync(manifestPath, manifest, 'utf8')
}

const source = readFileSync(sourcePath, 'utf8')
const rawPath = join(imageDir, `${name}.raw.svg`)
const adaptive = join(imageDir, `${name}.svg`)
const host = join(imageDir, `${name}.host.svg`)

if (!check) {
  const raw = await fetchKrokiSvg(source)
  writeFileSync(rawPath, raw, 'utf8')
}

if (!existsSync(rawPath)) {
  throw new Error(`${basename(rawPath)} missing — run pnpm diagrams:demo-plantuml without --check`)
}

execFileSync(process.execPath, [
  adapter,
  '--manifest', manifestPath,
  '--dual-output',
  ...(check ? ['--check'] : []),
  rawPath,
  '--output', adaptive,
  '--host-output', host,
], { stdio: 'inherit', cwd: root })

const cssMarker = '/* Demo PlantUML Themed SVG host vars (lightbox-compose)'
let css = existsSync(hostCssPath) ? readFileSync(hostCssPath, 'utf8') : ''
const block = hostCssBlock()
if (css.includes(cssMarker)) {
  css = css.replace(/\/\* Demo PlantUML Themed SVG host vars \(lightbox-compose\)[\s\S]*?(?=\n\/\*|$)/, block)
} else {
  css = `${css.trimEnd()}\n\n${block}`
}
if (check) {
  if (!existsSync(hostCssPath) || !readFileSync(hostCssPath, 'utf8').includes(cssVar('color.text.primary'))) {
    throw new Error(`${basename(hostCssPath)} missing demo PlantUML host vars — run pnpm diagrams:demo-plantuml`)
  }
} else {
  writeFileSync(hostCssPath, css.endsWith('\n') ? css : `${css}\n`, 'utf8')
}
